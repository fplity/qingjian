    fun build(
        articleId: Int,
        content: List<String>,
        translations: List<String>
    ): List<AnnotatedSentence> {
        val sources = content.flatMap(::splitSentences)
        val directTranslations = sentenceTranslationOverrides[articleId]
        require(directTranslations == null || directTranslations.size == sources.size) {
            "Article $articleId has ${sources.size} source sentences but ${directTranslations?.size} direct translations"
        }
        return sources.mapIndexed { sentenceIndex, source ->
            val sentenceId = "article-$articleId-sentence-${sentenceIndex + 1}"
            AnnotatedSentence(
                id = sentenceId,
                translationId = "article-$articleId-translation-${sentenceIndex + 1}",
                source = source,
                translation = directTranslations?.get(sentenceIndex)
                    ?: translations.getOrNull(sentenceIndex)
                    ?: translations.firstOrNull().orEmpty(),
                hasDirectTranslation = directTranslations?.getOrNull(sentenceIndex) != null ||
                    translations.size == sources.size,
                words = buildWords(sentenceId, source)
            )
        }
    }

    private fun buildWords(sentenceId: String, source: String): List<AnnotatedWord> {
        val words = mutableListOf<AnnotatedWord>()
        var offset = 0
        while (offset < source.length) {
            val glossaryMatch = termGlosses.firstOrNull { source.startsWith(it.text, offset) }
            val gloss = glossaryMatch ?: source[offset].takeIf { it.isChinese() }?.let {
                Gloss(it.toString(), "“$it”在本句中的具体含义需结合整句翻译理解。")
            }
            if (gloss == null) {
                offset++
                continue
            }
            val end = offset + gloss.text.length
            val occurrence = words.size + 1
            words += AnnotatedWord(
                id = "$sentenceId-word-$occurrence",
                glossId = "$sentenceId-gloss-$occurrence",
                source = gloss.text,
                start = offset,
                endExclusive = end,
                gloss = gloss.explanation
            )
            offset = end
        }
        return words
    }

    private fun splitSentences(line: String): List<String> {
        val result = mutableListOf<String>()
        var start = 0
        line.forEachIndexed { index, character ->
            if (character in sentenceEndings) {
                var end = index + 1
                while (end < line.length && line[end] in closingQuotes) end++
                val sentence = line.substring(start, end).trim()
                if (sentence.isNotEmpty()) result += sentence
                start = end
            }
        }
        val remainder = line.substring(start).trim()
        if (remainder.isNotEmpty()) result += remainder
        return result
    }

    private fun Char.isChinese(): Boolean = this in '\u3400'..'\u9fff'

